"""Copy the shared code (common/) into each extension and the dashboard.

An extension can only load files inside its own folder, so the one source of truth in common/
is copied into extension/ (the one Praise extension: family or personal, decided by the pairing code) and dashboard/. Run after
editing anything in common/:  python scripts/sync_common.py   (praise.bat does this on every start)
"""
import filecmp
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUDDY = ["companion.js", "companion-ui.js", "chat-ui.js", "companion.css", "pet.js", "pet-control.js"]
# (file in common/, folder it is copied into)
TARGETS = {
    "extension": [(f, ".") for f in ["lib.js", "protections.js", "sensitive.js", "passwords.js", "guard-control.js"] + BUDDY],
    "dashboard": [("companion.js", "js"), ("companion-ui.js", "js"), ("chat-ui.js", "js"), ("companion.css", "css")],
}


def generated() -> dict:
    """Files built from common/ rather than copied. The page buddy runs as a content script, which can't link a
    stylesheet without the page's rules getting a say, so its CSS ships as a string inside a script."""
    css = (ROOT / "common" / "companion.css").read_text(encoding="utf-8")
    text = "// Generated by scripts/sync_common.py from common/companion.css. Do not edit.\nself.PraiseBuddyCSS = " + json.dumps(css) + ";\n"
    return {"extension/companion-css.js": text}


def main(check_only=False) -> int:
    drift = 0
    for rel, text in generated().items():
        dst = ROOT / rel
        if dst.exists() and dst.read_text(encoding="utf-8") == text:
            continue
        drift += 1
        if check_only:
            print(f"out of date: {rel}")
        else:
            dst.write_text(text, encoding="utf-8", newline="\n")
            print(f"generated {rel}")
    for target, files in TARGETS.items():
        for name, folder in files:
            src, dst = ROOT / "common" / name, ROOT / target / folder / name
            if dst.exists() and filecmp.cmp(src, dst, shallow=False):
                continue
            drift += 1
            if check_only:
                print(f"out of date: {target}/{folder}/{name}")
            else:
                dst.parent.mkdir(exist_ok=True)
                shutil.copyfile(src, dst)
                print(f"synced {target}/{folder}/{name}")
    return drift if check_only else 0


if __name__ == "__main__":
    sys.exit(1 if main("--check" in sys.argv) else 0)
