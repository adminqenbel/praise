// Writes the declarativeNetRequest rule files for the personal (Shield) side of Praise from common/protections.js,
// and the page-world hardening script. Run after editing the tracker lists or the privacy techniques:
//   node scripts/build_rules.js
const fs = require("fs");
const path = require("path");
const P = require("../common/protections.js");

const out = path.join(__dirname, "..", "extension", "rules");
fs.mkdirSync(out, { recursive: true });

function write(name, rules, kind) {
  const problems = P.checkRules(rules, "static");
  if (problems.length) throw new Error(`${name}: ${problems.join("; ")}`);
  fs.writeFileSync(path.join(out, `${name}.json`), JSON.stringify(rules, null, 1) + "\n");
  console.log(`wrote extension/rules/${name}.json (${rules.length} rule${rules.length === 1 ? "" : "s"}${kind ? ", " + kind : ""})`);
}

// Block lists (trackers, fingerprint): one rule each, listing the domains. Chrome loads these as static network-blocking rules.
for (const [name, rules] of Object.entries(P.buildRulesets())) write(name, rules, `${rules[0].condition.requestDomains.length} domains`);
// Privacy techniques (tracking-parameter stripping, GPC / DNT headers, referrer trimming, HTTPS upgrade): one ruleset each so
// the extension can enable them one by one with updateEnabledRulesets. All start disabled in the manifest.
for (const [name, rules] of Object.entries(P.buildPrivacyRulesets())) write(name, rules);

// The same hardening the extension can inject into pages, with every default technique on. Register it as a MAIN-world
// content script at document_start; use P.hardeningSource(options) for a customised copy.
const harden = "// Generated by scripts/build_rules.js from common/protections.js (installHardening). Do not edit.\n" +
  P.hardeningSource(P.TECHNIQUE_DEFAULTS.harden);
fs.writeFileSync(path.join(__dirname, "..", "extension", "harden-main.js"), harden);
console.log("wrote extension/harden-main.js");
